import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const [name] = process.argv.slice(2);
const symbols = {
  cli: "VERSION",
  sdk: "SDK_VERSION",
  worker: "DO_CODE_VERSION",
};
if (!Object.hasOwn(symbols, name))
  throw new Error("Expected cli, sdk, or worker");
const root = new URL("../", import.meta.url);
const pkg = JSON.parse(
  readFileSync(new URL(`packages/${name}/package.json`, root), "utf8"),
);
const revision =
  process.env.TILA_BUILD_REVISION ||
  execFileSync("git", ["rev-parse", "HEAD"], {
    cwd: fileURLToPath(root),
    encoding: "utf8",
  }).trim();
const value = name === "worker" ? revision : pkg.version;
const output = new URL(`packages/${name}/src/version.ts`, root);
let content = `// Generated by scripts/generate-version.mjs. Do not edit.\nexport const ${symbols[name]} = ${JSON.stringify(value)};\n`;
// The Worker package version is private; the root marker is the product release.
if (name === "worker") {
  const product = JSON.parse(
    readFileSync(new URL("package.json", root), "utf8"),
  );
  content += `export const PRODUCT_VERSION = ${JSON.stringify(product.version)};\nexport const BUILD_COMMIT = ${JSON.stringify(revision)};\n`;
}
let previous;
try {
  previous = readFileSync(output, "utf8");
} catch (error) {
  if (error.code !== "ENOENT") throw error;
}
if (previous !== content) writeFileSync(output, content);
